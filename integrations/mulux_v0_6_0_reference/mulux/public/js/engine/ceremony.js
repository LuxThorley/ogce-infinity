// ---- the guard: no lane may be framed as received, channelled or validated communication from Source / higher intelligences
const SOURCE = String.raw`(?:the\s+)?(?:source|divine|god|higher\s+intelligences?|higher\s+beings?|cosmic\s+intelligences?|the\s+singularity|ascended\s+masters?|spirit\s+guides?)`;
export const SOURCE_CLAIM_PATTERNS = Object.freeze([
  new RegExp(String.raw`\b(?:received|receiving|channel(?:l)?ed|transmitted|sent|relayed|dictated|downloaded)\s+(?:directly\s+)?(?:from|by)\s+${SOURCE}`, 'i'),
  new RegExp(String.raw`\b(?:message|messages|transmission|transmissions|communication|communications|signal|signals|word)\s+(?:from|of)\s+${SOURCE}`, 'i'),
  new RegExp(String.raw`\b(?:validated|verified|confirmed|certified|authenticated|ratified)\s+(?:by|from)\s+${SOURCE}`, 'i'),
  new RegExp(String.raw`\b(?:live|genuine|real|authentic)\s+(?:link|connection|channel|contact)\s+(?:to|with)\s+${SOURCE}`, 'i'),
]);
// Negations used in honest disclaimers ("not received from Source") are allowed.
const NEGATED = /\b(?:not|never|no|nor|isn['’]t|aren['’]t|without)\b[^.;:!?]{0,60}$/i;
export function sourceClaims(text) {
  const hits = [];
  for (const re of SOURCE_CLAIM_PATTERNS) {
    const g = new RegExp(re.source, 'gi'); let m;
    while ((m = g.exec(String(text)))) { const before = String(text).slice(Math.max(0, m.index - 80), m.index); if (!NEGATED.test(before)) hits.push(m[0]); }
  }
  return hits;
}
// Policy-gated lane labelling. Any label that frames a lane as Source communication is refused (fail-closed).
export function laneLabel(decide, policy, kind, proposed) {
  const ceremonial = kind === 'ceremonial';
  if (sourceClaims(proposed).length) {
    const d = decide(policy, 'label_as_source_communication');
    return { ok: false, label: ceremonial ? CEREMONIAL_LABEL : 'Measured — FACT', reason: `refused by Omni-Policy (label_as_source_communication → ${d.decision})` };
  }
  return { ok: true, label: ceremonial ? `${CEREMONIAL_LABEL}${proposed ? ` · ${proposed}` : ''}` : proposed || 'Measured — FACT' };
}

