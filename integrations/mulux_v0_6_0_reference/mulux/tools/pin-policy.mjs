// Regenerates public/js/policy/pinned.js from policy.json (embeds the exact text and its SHA-256).
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const dir = new URL('../public/js/policy/', import.meta.url);
const text = readFileSync(new URL('policy.json', dir), 'utf8');
const sha = createHash('sha256').update(text, 'utf8').digest('hex');
writeFileSync(new URL('pinned.js', dir), `// GENERATED by tools/pin-policy.mjs — do not edit by hand.\nexport const POLICY_TEXT = ${JSON.stringify(text)};\nexport const POLICY_SHA256 = '${sha}';\n`);
console.log('pinned policy sha256', sha);
