// Copies the authoritative world simulation (JS port of ogce4/v70/runtime.py) into the static site so offline solo play
// runs the SAME rules as the server. Run after editing cloudflare/src/runtime.js or pyjson.js; a test checks they match.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const root = new URL('../../', import.meta.url);
mkdirSync(new URL('web/js/vendor/', root), { recursive: true });
for (const f of ['runtime.js', 'pyjson.js']) {
  const src = readFileSync(new URL(`cloudflare/src/${f}`, root), 'utf8');
  writeFileSync(new URL(`web/js/vendor/${f}`, root), `// GENERATED by cloudflare/tools/vendor_runtime.mjs from cloudflare/src/${f}. Do not edit here.\n` + src);
}
console.log('vendored runtime.js + pyjson.js');
